import React, { useEffect, useState } from 'react';
import { motion } from 'framer-motion';
import { FiCpu, FiCheckCircle, FiAlertCircle, FiBookOpen, FiShield } from 'react-icons/fi';

const COMPLIANCE_STYLES = {
  ACCEPT: { color: '#22c55e', bg: 'rgba(34,197,94,0.1)', border: 'rgba(34,197,94,0.3)', label: '✅ ACCEPT' },
  FAILED: { color: '#fbbf24', bg: 'rgba(251,191,36,0.1)', border: 'rgba(251,191,36,0.3)', label: '⚠️ FAILED' },
  REJECT: { color: '#ef4444', bg: 'rgba(239,68,68,0.1)', border: 'rgba(239,68,68,0.3)', label: '❌ REJECT' },
};

/**
 * Typewriter effect for text display
 */
const useTypewriter = (text, speed = 18, active = false) => {
  const [displayed, setDisplayed] = useState('');
  const [done, setDone] = useState(false);

  useEffect(() => {
    if (!active || !text) {
      setDisplayed(text || '');
      setDone(true);
      return;
    }
    setDisplayed('');
    setDone(false);
    let i = 0;
    const interval = setInterval(() => {
      setDisplayed(text.slice(0, i + 1));
      i++;
      if (i >= text.length) {
        clearInterval(interval);
        setDone(true);
      }
    }, speed);
    return () => clearInterval(interval);
  }, [text, speed, active]);

  return { displayed, done };
};

const DEFAULT_COMPLIANCE_STYLE = {
  color: '#ef4444',
  bg: 'rgba(239,68,68,0.1)',
  border: 'rgba(239,68,68,0.3)',
  label: '❌ REJECT',
};

export default function AISummary({ aiSummary, fraudAssessment }) {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    if (aiSummary) {
      const timer = setTimeout(() => setVisible(true), 300);
      return () => clearTimeout(timer);
    }
  }, [aiSummary]);

  const summaryBody = aiSummary?.body ?? '';
  const { displayed: displayedBody } = useTypewriter(summaryBody, 12, visible);

  if (!aiSummary) return null;

  const finalStatus = aiSummary?.finalDecision || 'REJECT';
  
  console.log('AISummary data:', aiSummary);
  console.log('Final Decision:', finalStatus);

  const complianceStyle = COMPLIANCE_STYLES?.[finalStatus] ?? DEFAULT_COMPLIANCE_STYLE;

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.5 }}
      className="glass-card p-6 space-y-5"
      id="ai-summary-card"
    >
      {/* Header */}
      <div className="flex items-center gap-3">
        <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-violet-500/20 to-blue-500/20 border border-violet-500/30 flex items-center justify-center">
          <FiCpu className="text-violet-400 text-lg" />
        </div>
        <div>
          <h3 className="text-white font-bold text-base">AI Compliance Summary</h3>
          <p className="text-xs text-slate-500">Generated by Gemini 2.5 Flash</p>
        </div>
        <div className="ml-auto">
          <span
            className="text-xs px-3 py-1.5 rounded-full font-semibold"
            style={{
              color: complianceStyle.color,
              background: complianceStyle.bg,
              border: `1px solid ${complianceStyle.border}`,
            }}
            id="compliance-status-badge"
          >
            {complianceStyle.label}
          </span>
        </div>
      </div>

      {/* Headline */}
      {aiSummary.headline && (
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          className="rounded-xl bg-blue-500/10 border border-blue-500/20 p-4"
        >
          <p className="text-blue-200 font-semibold text-sm leading-relaxed">
            {aiSummary.headline}
          </p>
        </motion.div>
      )}

      {/* Body (typewriter) */}
      <div className="text-slate-300 text-sm leading-7">
        <p className="whitespace-pre-line">
          {displayedBody}
          {!displayedBody.endsWith(aiSummary.body) && (
            <span className="animate-pulse text-blue-400">|</span>
          )}
        </p>
      </div>

      {/* Key Findings */}
      {aiSummary.keyFindings && aiSummary.keyFindings.length > 0 && (
        <div className="space-y-2">
          <div className="flex items-center gap-2">
            <FiBookOpen className="text-slate-500 text-sm" />
            <h4 className="text-xs font-semibold text-slate-400 uppercase tracking-wider">Key Findings</h4>
          </div>
          {aiSummary.keyFindings.map((finding, i) => (
            <motion.div
              key={i}
              initial={{ opacity: 0, x: -10 }}
              animate={{ opacity: 1, x: 0 }}
              transition={{ delay: i * 0.1 + 0.5 }}
              className="flex items-start gap-2.5 text-sm"
            >
              <FiCheckCircle className="text-blue-400 flex-shrink-0 mt-0.5" />
              <span className="text-slate-300">{finding}</span>
            </motion.div>
          ))}
        </div>
      )}

    {/* Recommendation */}
      {aiSummary.recommendation && (
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ delay: 0.8 }}
          className="rounded-xl border border-amber-500/20 bg-amber-500/5 p-4 flex items-start gap-2.5"
        >
          <FiAlertCircle className="text-amber-400 flex-shrink-0 mt-0.5" />
          <div>
            <p className="text-xs font-semibold text-amber-400 mb-1">Recommendation</p>
            <p className="text-sm text-amber-200/80">{aiSummary.recommendation}</p>
          </div>
        </motion.div>
      )}

      {/* Fraud & Authenticity Assessment */}
      {fraudAssessment && (
        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 1 }}
          className={`rounded-xl border p-5 ${fraudAssessment.isFraudulent ? 'bg-red-950/40 border-red-900/50' : 'bg-slate-800/50 border-slate-700/50'}`}
        >
          <div className="flex items-center justify-between mb-3">
            <h4 className="text-sm font-bold text-white flex items-center gap-2">
              <FiShield className={fraudAssessment.isFraudulent ? 'text-red-400' : 'text-emerald-400'} />
              Authenticity Analysis
            </h4>
            <div className={`px-2.5 py-1 rounded-full text-xs font-bold border ${fraudAssessment.isFraudulent ? 'bg-red-500/20 text-red-400 border-red-500/30' : 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30'}`}>
              Score: {fraudAssessment.authenticityScore}%
            </div>
          </div>
          <p className="text-sm text-slate-300 leading-relaxed mb-3">
            {fraudAssessment.fraudAnalysis}
          </p>
          {fraudAssessment.primaryRiskFactor && fraudAssessment.primaryRiskFactor !== 'None' && (
            <div className="text-xs bg-black/20 rounded p-2 text-slate-400">
              <span className="font-semibold text-slate-300">Primary Risk Factor:</span> {fraudAssessment.primaryRiskFactor}
            </div>
          )}
        </motion.div>
      )}
    </motion.div>
  );
}
